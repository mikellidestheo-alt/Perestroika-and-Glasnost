export interface Outlook {
  forecast: string;
  lines: { label: string; text: string; level: Tier }[];
}

/** Picture of the country five years on, derived from the final metrics. */
export function outlook(m: Metrics): Outlook {
  const e = tier(m.economy);
  const g = tier(m.glasnost);
  const p = tier(m.party);
  const t = tier(m.trust);
  let forecast = 'Прогноз: неустойчивое равновесие. Любой кризис может склонить чашу весов в любую сторону.';
  if (e === 0 && t === 0) forecast = 'Прогноз: социальный взрыв. Бедность и разочарование делают массовые протесты почти неизбежными.';
  else if (g === 2 && p === 0) forecast = 'Прогноз: открытое столкновение реформаторов и консерваторов, которое может закончиться силовым решением.';
  else if (e === 0) forecast = 'Прогноз: затяжной экономический кризис. Страна зависит от импорта и займов, а регионы начинают жить сами по себе.';
  else if (t === 0) forecast = 'Прогноз: власть теряет легитимность. Люди перестают верить любым обещаниям.';
  else if (e >= 1 && t >= 1 && p >= 1 && g >= 1) forecast = 'Прогноз: есть шанс на мягкую трансформацию. Реформы продолжаются, но ценой трудных компромиссов.';
  return {
    forecast,
    lines: [
      { label: 'Экономика', text: OUTLOOK_TEXT.economy[e], level: e },
      { label: 'Гласность', text: OUTLOOK_TEXT.glasnost[g], level: g },
      { label: 'Поддержка партии', text: OUTLOOK_TEXT.party[p], level: p },
      { label: 'Народное доверие', text: OUTLOOK_TEXT.trust[t], level: t },
    ],
  };
}

